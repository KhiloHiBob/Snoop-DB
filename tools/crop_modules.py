#!/usr/bin/env python3
"""Crop per-module DB knowledge out of the Bob monolith into db-dog skills.

    python tools/crop_modules.py ~/IdeaProjects/hibob

For each module under app/com/hibob/<module>/ it reads the module AGENTS.md files and the DB docs
(DatabaseSchema.md, *Db*.md, DBQueries.md under .doc/) and writes knowledge_local/modules/<module>.md.
Output is git-ignored (Bob-internal). Files starting with "<!-- curated" are never overwritten.
The agent loads a module skill when the question mentions the module (see agent/modules.py).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "knowledge_local" / "modules"
DB_HEADING = re.compile(r"(db|database|table|schema|sql|migration|persist|repositor|column|index|entit|data model|query)", re.I)
DB_DOC = re.compile(r"(schema|db|quer|fields|entit|table|model|foundation|overview|setup|polic|cycle|entries|timesheet|reference)", re.I)
HAS_TABLES = re.compile(r"(create table|\|\s*column|\bcompany_id\b)", re.I)
ORIENT = re.compile(r"(quick|overview|package structure|structure|purpose)", re.I)
MAX_MODULE = 70000   # chars per module skill
MAX_AGENTS = 9000     # chars of AGENTS.md material per module
MAX_DOC = 40000       # chars per DB doc


def sections(md: str) -> list[tuple[str, str]]:
    parts = re.split(r"(?m)^(#{1,3} .*)$", md)
    out = [("", parts[0])]
    out += [(parts[i], parts[i + 1]) for i in range(1, len(parts) - 1, 2)]
    return out


def crop_agents(path: Path) -> str:
    md = path.read_text(errors="replace")
    secs = sections(md)
    keep = [secs[0][1].strip()[:1500]] if secs[0][1].strip() else []
    for head, body in secs[1:]:
        if DB_HEADING.search(head) or ORIENT.search(head):
            keep.append(f"{head}\n{body.strip()}")
    if len(keep) <= 1 and len(secs) > 1:   # no DB section: keep the title + first section as orientation
        keep.append(f"{secs[1][0]}\n{secs[1][1].strip()[:1500]}")
    return "\n\n".join(keep)[:MAX_AGENTS]


def build(module_dir: Path, root: Path) -> str | None:
    agents = sorted(module_dir.rglob("AGENTS.md"), key=lambda p: len(p.parts))
    docs = [p for p in sorted(module_dir.rglob("*.md")) if ".doc" in p.parts and DB_DOC.search(p.stem)
            and p.stat().st_size < 120_000 and HAS_TABLES.search(p.read_text(errors="replace"))]
    docs.sort(key=lambda p: (not re.search(r"(schema|db)", p.stem, re.I), p.stat().st_size))
    if not agents and not docs:
        return None
    slug = module_dir.name
    out = [f"<!-- generated by tools/crop_modules.py from {module_dir.relative_to(root)} -->",
           f"# Module skill: {slug}",
           f"Source: `{module_dir.relative_to(root)}/`. Cropped from the monolith docs; code and the live schema win if they differ.",
           "Every table is tenant-scoped: filter on `company_id`, and quote `employee_id` (it is a string)."]
    used = 0
    for d in docs:
        if used > MAX_MODULE:
            break
        used += min(d.stat().st_size, MAX_DOC)
        out.append(f"\n## DB doc: {d.relative_to(module_dir)}\n{d.read_text(errors='replace')[:MAX_DOC]}")
    budget = MAX_AGENTS * 2
    for a in agents:
        if budget <= 0:
            break
        text = crop_agents(a)[:budget]
        budget -= len(text)
        if text.strip():
            out.append(f"\n## Agent guide: {a.relative_to(module_dir)}\n{text}")
    return "\n".join(out) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    root = Path(sys.argv[1]).expanduser().resolve()
    base = root / "app" / "com" / "hibob"
    if not base.is_dir():
        print(f"not a monolith checkout: {base}")
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    written, skipped = [], []
    for d in sorted(p for p in base.iterdir() if p.is_dir()):
        text = build(d, root)
        if not text:
            continue
        target = OUT / f"{d.name}.md"
        if target.exists() and target.read_text().startswith("<!-- curated"):
            skipped.append(d.name)
            continue
        target.write_text(text)
        written.append((d.name, len(text)))
    print(f"wrote {len(written)} module skills to {OUT}")
    for name, size in written:
        print(f"  {name:<18} {size // 1024:>4} KB")
    if skipped:
        print("kept curated:", ", ".join(skipped))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
